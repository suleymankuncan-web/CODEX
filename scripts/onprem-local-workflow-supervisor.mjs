function commandPath(value, label) {
  if (typeof value !== 'string' || value.length === 0 || /[\0\r\n]/.test(value)) throw new TypeError(`${label} is invalid`)
  return value
}

export function buildWorkflowSupervisor({ bashPath, setsidPath }) {
  const bash = commandPath(bashPath, 'bash path')
  const setsid = commandPath(setsidPath, 'setsid path')
  return [
    'set -eu',
    'marker="$1"; leader_marker="$2"; containment_marker="$3"; body="$4"; deadline="$5"',
    'rm -f -- "$marker" "$leader_marker" "$containment_marker"',
    // The inner shell writes its own $$ after setsid has established the
    // session. This avoids treating a possible setsid fork/wait helper as
    // the process-group leader that must be terminated.
    `${setsid} --wait ${bash} --noprofile --norc -e -u -o pipefail -c 'leader_marker="$1"; body="$2"; printf "%s\\n" "$$" > "$leader_marker"; exec ${bash} --noprofile --norc -e -u -o pipefail -c "$body"' offline-workflow-child "$leader_marker" "$body" &`,
    'child="$!"',
    'leader=""',
    'watchdog=""',
    'stop_watchdog() {',
    '  if test -n "$watchdog"; then',
    '    kill -TERM "$watchdog" 2>/dev/null || true',
    '    wait "$watchdog" 2>/dev/null || true',
    '  fi',
    '  watchdog=""',
    '}',
    'abort_supervisor() {',
    '  trap "" TERM INT HUP',
    '  stop_watchdog',
    '  if test -n "$leader"; then',
    '    kill -TERM -- "-$leader" 2>/dev/null || true',
    '    sleep 1',
    '    kill -KILL -- "-$leader" 2>/dev/null || true',
    '  elif test -n "$child"; then',
    '    kill -TERM "$child" 2>/dev/null || true',
    '    sleep 1',
    '    kill -KILL "$child" 2>/dev/null || true',
    '  fi',
    '  if test -n "$child"; then wait "$child" 2>/dev/null || true; fi',
    '  exit 125',
    '}',
    'trap abort_supervisor TERM INT HUP',
    'attempt=0',
    'while test "$attempt" -lt 20 && test -z "$leader"; do',
    '  if test -s "$leader_marker"; then IFS= read -r leader < "$leader_marker"; fi',
    '  test -n "$leader" || sleep 0.05',
    '  attempt=$((attempt + 1))',
    'done',
    'case "$leader" in ""|*[!0-9]*) abort_supervisor ;; esac',
    '(',
    '  watchdog_timer=""',
    '  cleanup_watchdog() {',
    '    trap - EXIT TERM INT HUP',
    '    if test -n "$watchdog_timer"; then',
    '      kill -TERM "$watchdog_timer" 2>/dev/null || true',
    '      wait "$watchdog_timer" 2>/dev/null || true',
    '    fi',
    '  }',
    '  trap "cleanup_watchdog; exit 0" TERM INT HUP',
    '  trap cleanup_watchdog EXIT',
    '  sleep "$deadline" &',
    '  watchdog_timer="$!"',
    '  if ! wait "$watchdog_timer"; then exit 0; fi',
    '  : > "$marker"',
    '  kill -TERM -- "-$leader" 2>/dev/null || true',
    '  sleep 10 &',
    '  watchdog_timer="$!"',
    '  if ! wait "$watchdog_timer"; then exit 0; fi',
    '  kill -KILL -- "-$leader" 2>/dev/null || true',
    ') </dev/null >/dev/null 2>&1 &',
    'watchdog="$!"',
    'set +e; wait "$child"; status="$?"; set -e',
    'if test -f "$marker"; then wait "$watchdog" || true; watchdog=""; else stop_watchdog; fi',
    // A child can reap before descendants do. Poll the complete process
    // group, then TERM/KILL the negative PGID and poll again before recovery.
    'group_gone=0',
    'attempt=0',
    'while test "$attempt" -lt 20; do',
    '  if kill -0 -- "-$leader" 2>/dev/null; then sleep 0.25; else group_gone=1; break; fi',
    '  attempt=$((attempt + 1))',
    'done',
    'if test "$group_gone" -ne 1; then',
    '  kill -TERM -- "-$leader" 2>/dev/null || true',
    '  sleep 1',
    '  kill -KILL -- "-$leader" 2>/dev/null || true',
    '  wait "$child" 2>/dev/null || true',
    '  attempt=0',
    '  while test "$attempt" -lt 20; do',
    '    if kill -0 -- "-$leader" 2>/dev/null; then sleep 0.25; else group_gone=1; break; fi',
    '    attempt=$((attempt + 1))',
    '  done',
    'fi',
    'printf "%s\\n" "$group_gone" > "$containment_marker"',
    'if test "$group_gone" -ne 1; then exit 125; fi',
    'exit "$status"',
  ].join('\n')
}
